import assert from "node:assert/strict";
import {registerHooks} from "node:module";
import {PrismaClient} from "@prisma/client";
import bcrypt from "bcryptjs";
registerHooks({resolve(specifier,context,nextResolve){
 if(specifier==="next/server")return nextResolve(new URL("./ci-route-runtime-shim.mjs",import.meta.url).href,context);
 if(specifier==="next-auth/providers/credentials")return nextResolve(new URL("./ci-credentials-provider-shim.mjs",import.meta.url).href,context);
 if(specifier==="next-auth")return nextResolve(new URL("./ci-two-factor-session-shim.mjs",import.meta.url).href,context);
 if(specifier==="next-auth/jwt")return nextResolve(new URL("./ci-two-factor-jwt-shim.mjs",import.meta.url).href,context);
 if(specifier==="resend")return nextResolve(new URL("./ci-resend-shim.mjs",import.meta.url).href,context);
 if(specifier.startsWith("@/lib/"))return nextResolve(new URL("../src/lib/"+specifier.slice(6)+".ts",import.meta.url).href,context);
 if(specifier.startsWith("./")&&context.parentURL?.includes("/src/lib/")&&!/\.[cm]?[jt]s$/.test(specifier))return nextResolve(new URL(specifier+".ts",context.parentURL).href,context);
 return nextResolve(specifier,context);
}});
if(!process.env.DATABASE_URL?.includes("zenvest_ci"))throw Error("Disposable CI database required");
process.env.TWO_FACTOR_ENCRYPTION_KEY="a1".repeat(32);
process.env.RESEND_API_KEY="offline-key";
process.env.EMAIL_FROM="ci@example.invalid";
const {makeChallenge,newTotpSecret,totpAt,validTotpStep,encryptSecret,decryptSecret,verifyChallenge,consumeRecoveryCode,IDLE_MS}=await import("../src/lib/two-factor.ts");
const {POST:start}=await import("../src/app/api/auth/2fa/start/route.ts");
const {POST:staffEnroll}=await import("../src/app/api/auth/2fa/staff-enroll/route.ts");
const {POST:manage,GET:status}=await import("../src/app/api/account/2fa/route.ts");
const {POST:activity}=await import("../src/app/api/session/activity/route.ts");
const {deliveries}=await import("./ci-resend-shim.mjs");
const prisma=new PrismaClient();
const userId="ci_security_user",password="StrongPass123!";
const req=payload=>new Request("https://ci.invalid/api/security",{method:"POST",body:JSON.stringify(payload)});
const login=payload=>start(req(payload)),settings=payload=>manage(req(payload));
const emailCode=()=>{const match=deliveries.at(-1)?.text?.match(/\b\d{6}\b/);assert.ok(match,"offline delivery includes a six-digit code");return match[0]};
try{
 await prisma.user.create({data:{id:userId,handle:"sec2fa",email:"ci-security@example.invalid",name:"Security fixture",passwordHash:await bcrypt.hash(password,10),emailVerifiedAt:new Date()}});
 assert.equal(IDLE_MS,1800000);
 assert.equal(totpAt("GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ",1),"287082","RFC 6238 SHA1 vector (6 digits)");
 assert.equal(totpAt("GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ",37037036),"081804","RFC 6238 vector at 1111111109");
 const secret=newTotpSecret();assert.match(secret,/^[A-Z2-7]{32}$/);
 const encrypted=encryptSecret(secret);assert.notEqual(encrypted,secret);assert.equal(decryptSecret(encrypted),secret);
 assert.equal(validTotpStep(secret,"abc"),null);
 assert.equal((await login({email:"bad",password:"wrong"})).status,401);
 assert.equal((await login({email:"ci-security@example.invalid",password:"wrong"})).status,401);
 assert.deepEqual(await (await login({email:"ci-security@example.invalid",password})).json(),{requires2fa:false});
 assert.deepEqual(await (await status()).json(),{enabled:false,method:null,methods:[]});
 assert.equal((await settings({action:"setup",password:"wrong",method:"APP"})).status,403);
 assert.equal((await settings({action:"setup",password,method:"OTHER"})).status,400);
 const setup=(await (await settings({action:"setup",password,method:"APP"})).json());
 assert.equal(setup.method,"APP");assert.ok(setup.challengeId);assert.ok(setup.uri.startsWith("otpauth://totp/"));
 const badEnable=await settings({action:"enable",password,challengeId:setup.challengeId,code:"000foo"});assert.equal(badEnable.status,400);
 const step=Math.floor(Date.now()/30000),code=totpAt(setup.secret,step);
 const enabled=await settings({action:"enable",password,challengeId:setup.challengeId,code});
 assert.equal(enabled.status,200);
 const enabledData=await enabled.json().catch(()=>null);
 assert.equal(enabledData.recoveryCodes.length,8);
 assert.equal((await prisma.twoFactor.findUniqueOrThrow({where:{userId}})).method,"APP");
 assert.deepEqual(await (await status()).json(),{enabled:true,method:"APP",methods:["APP"]});
 // Enroll email alongside the original app, preserving APP as the default.
 const addEmail=(await (await settings({action:"add-method",password,method:"EMAIL"})).json());
 assert.ok(addEmail.challengeId);
 const confirmEmail=await settings({action:"confirm-method",password,challengeId:addEmail.challengeId,code:emailCode()});
 assert.equal(confirmEmail.status,200);
 assert.deepEqual(await (await status()).json(),{enabled:true,method:"APP",methods:["EMAIL","APP"]});
 assert.equal((await settings({action:"set-default",password,method:"EMAIL"})).status,200);
 assert.equal((await prisma.twoFactor.findUniqueOrThrow({where:{userId}})).method,"EMAIL");
 assert.equal((await settings({action:"set-default",password,method:"APP"})).status,200);
 assert.equal((await prisma.twoFactor.findUniqueOrThrow({where:{userId}})).method,"APP");
 const alternate=(await (await login({email:"ci-security@example.invalid",password,method:"EMAIL"})).json());
 assert.equal(alternate.method,"APP","requesting an alternate login method must not override the persisted default");
 const removalRequest=(await (await settings({action:"remove-method-code",password,method:"EMAIL"})).json());
 assert.ok(removalRequest.challengeId);
 assert.equal((await settings({action:"remove-method",password,method:"EMAIL",challengeId:removalRequest.challengeId,code:emailCode()})).status,200);
 assert.deepEqual(await (await status()).json(),{enabled:true,method:"APP",methods:["APP"]});
 assert.equal((await settings({action:"remove-method",password,method:"APP",code:"000000"})).status,403,"the final method still requires a valid code");

 const challenge=(await (await login({email:"ci-security@example.invalid",password})).json());
 assert.equal(challenge.method,"APP");assert.ok(challenge.challengeId);
 assert.equal(await verifyChallenge(challenge.challengeId,userId,"LOGIN","123abc"),false);
 assert.equal(await verifyChallenge(challenge.challengeId,userId,"LOGIN",totpAt(setup.secret,step+1)),true);
 assert.equal(await verifyChallenge(challenge.challengeId,userId,"LOGIN",totpAt(setup.secret,step+1)),false,"TOTP challenge cannot be reused");
 assert.equal(await consumeRecoveryCode(userId,enabledData.recoveryCodes[0]),true);
 assert.equal(await consumeRecoveryCode(userId,enabledData.recoveryCodes[0]),false);
 assert.equal((await settings({action:"disable",password,code:enabledData.recoveryCodes[1]})).status,200);
 assert.equal((await status()).status,200);
 assert.equal((await (await status()).json()).enabled,false);
 const emailSetup=(await (await settings({action:"setup",password,method:"EMAIL"})).json());
 assert.equal(emailSetup.method,"EMAIL");
 const emailEnabled=await settings({action:"enable",password,challengeId:emailSetup.challengeId,code:emailCode()});
 assert.equal(emailEnabled.status,200);
 const emailChallenge=(await (await login({email:"ci-security@example.invalid",password})).json());
 assert.equal(emailChallenge.method,"EMAIL");
 const sentCode=emailCode();
 assert.equal(await verifyChallenge(emailChallenge.challengeId,userId,"LOGIN",sentCode),true);
 assert.equal(await verifyChallenge(emailChallenge.challengeId,userId,"LOGIN",sentCode),false,"Email codes are single use");
 const requestDisable=(await (await settings({action:"disable-code",password})).json());
 assert.ok(requestDisable.challengeId);
 assert.equal((await settings({action:"disable",password,challengeId:requestDisable.challengeId,code:emailCode()})).status,200);
 // Reset old disposable challenge fixtures before testing a separate onboarding session.
 await prisma.twoFactorChallenge.deleteMany({where:{userId,purpose:{in:["ENABLE","LOGIN"]}}});
 // Staff roles are additive; unenrolled staff cannot log in until 2FA setup completes.
 assert.equal((await staffEnroll(req({action:"setup",password,method:"APP",email:"ci-security@example.invalid"}))).status,403,"investor-only users enroll in Settings instead");
 const staffRole=await prisma.role.create({data:{key:"ci-security-staff"}});
 try{
  await prisma.userRole.create({data:{userId,roleId:staffRole.id,assignedBy:"ci-test-admin"}});
  assert.equal((await staffEnroll(req({action:"setup",password:"wrong",method:"APP",email:"ci-security@example.invalid"}))).status,401);
  assert.deepEqual(await (await login({email:"ci-security@example.invalid",password})).json(),{requiresEnrollment:true});
  const appStart=await (await staffEnroll(req({action:"setup",password,method:"APP",email:"ci-security@example.invalid"}))).json();
  assert.equal(appStart.method,"APP");assert.ok(appStart.secret&&appStart.uri);
  assert.equal((await staffEnroll(req({action:"confirm",password,method:"APP",challengeId:appStart.challengeId,code:"111abc",email:"ci-security@example.invalid"}))).status,400);
  const appConfirm=await staffEnroll(req({action:"confirm",password,method:"APP",challengeId:appStart.challengeId,code:totpAt(appStart.secret,Math.floor(Date.now()/30000)),email:"ci-security@example.invalid"}));
  assert.equal(appConfirm.status,200);
  assert.equal((await appConfirm.json()).recoveryCodes.length,8);
  assert.equal((await prisma.twoFactor.findUniqueOrThrow({where:{userId}})).method,"APP");
  assert.equal((await staffEnroll(req({action:"confirm",password,method:"APP",challengeId:appStart.challengeId,code:"123456",email:"ci-security@example.invalid"}))).status,409);
  assert.equal((await (await login({email:"ci-security@example.invalid",password})).json()).method,"APP");
  await prisma.twoFactor.delete({where:{userId}}); // Simulate staff account with 2FA removed; reenrollment is mandatory.
  assert.deepEqual(await (await login({email:"ci-security@example.invalid",password})).json(),{requiresEnrollment:true});
  const emailStart=await (await staffEnroll(req({action:"setup",password,method:"EMAIL",email:"ci-security@example.invalid"}))).json();
  assert.equal(emailStart.method,"EMAIL");
  const emailConfirm=await staffEnroll(req({action:"confirm",password,method:"EMAIL",challengeId:emailStart.challengeId,code:emailCode(),email:"ci-security@example.invalid"}));
  assert.equal(emailConfirm.status,200);
  assert.equal((await emailConfirm.json()).recoveryCodes.length,8);
  assert.equal((await (await login({email:"ci-security@example.invalid",password})).json()).method,"EMAIL");
 }finally{
  await prisma.userRole.deleteMany({where:{userId,roleId:staffRole.id}});
  await prisma.role.delete({where:{id:staffRole.id}});
 }
 await prisma.securitySession.create({data:{id:"ci_security_device",userId}});
 assert.equal((await activity(new Request("https://ci.invalid/api/session/activity",{method:"POST"}))).status,200);
 await prisma.securitySession.update({where:{id:"ci_security_device"},data:{lastActivityAt:new Date(Date.now()-31*60000)}});
 assert.equal((await activity(new Request("https://ci.invalid/api/session/activity",{method:"POST"}))).status,401,"idle session cannot be revived");
 console.log("Two-factor enrollment, email, TOTP, recovery, replay and server idle checks passed");
}finally{
 await prisma.securitySession.deleteMany({where:{userId}});
 await prisma.twoFactorChallenge.deleteMany({where:{userId}});
 await prisma.twoFactorRecoveryCode.deleteMany({where:{userId}});
 await prisma.twoFactor.deleteMany({where:{userId}});
 await prisma.user.deleteMany({where:{id:userId}});
 await prisma.$disconnect();
}
