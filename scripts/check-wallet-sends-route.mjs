import assert from "node:assert/strict";
import {PrismaClient} from "@prisma/client";
import {registerHooks} from "node:module";
const shim=new URL("./ci-route-runtime-shim.mjs",import.meta.url).href;
registerHooks({resolve(specifier,context,nextResolve){
 if(specifier==="next/server"||specifier==="@/lib/access")return nextResolve(shim,context);
 if(specifier==="server-only")return nextResolve(new URL("./ci-server-only-shim.mjs",import.meta.url).href,context);
 if(specifier.startsWith("@/lib/"))return nextResolve(new URL("../src/lib/"+specifier.slice(6)+".ts",import.meta.url).href,context);
 if(specifier.startsWith("./")&&context.parentURL?.includes("/src/lib/")&&!/\.[cm]?[jt]s$/.test(specifier))return nextResolve(new URL(specifier+".ts",context.parentURL).href,context);
 return nextResolve(specifier,context);
}});
if(!process.env.DATABASE_URL?.includes("zenvest_ci"))throw Error("CI database required");
const prisma=new PrismaClient();
const {POST}=await import("../src/app/api/wallet/sends/route.ts");
const senderId="ci_route_investor",recipientId="ci_send_recipient";
const senderHandle="send0001",recipientHandle="recv0001";
const call=data=>POST(new Request("http://ci.local/api/wallet/sends",{method:"POST",body:typeof data==="string"?data:JSON.stringify(data)}));
const k1="00000000-0000-4000-8000-000000000001",k2="00000000-0000-4000-8000-000000000002",k3="00000000-0000-4000-8000-000000000003";
try{
 await prisma.user.create({data:{id:senderId,name:"CI sender",email:"ci-send-sender@example.invalid",handle:senderHandle,passwordHash:"ci",emailVerifiedAt:new Date(),unallocated:50_000_000n}});
 await prisma.user.create({data:{id:recipientId,name:"CI recipient",email:"ci-send-recipient@example.invalid",handle:recipientHandle,passwordHash:"ci",emailVerifiedAt:new Date(),unallocated:10_000_000n}});
 await prisma.withdrawal.create({data:{id:"ci_send_reservation",userId:senderId,amountUsdcMicros:8_000_000n,grossUsdcMicros:10_000_000n,destinationAddress:"11111111111111111111111111111111",status:"PENDING"}});
 assert.equal((await call("{bad")).status,400);
 assert.equal((await call({handle:"@"+recipientHandle,amount:"0",idempotencyKey:k1})).status,400);
 assert.equal((await call({handle:"@"+recipientHandle,amount:"1.1234567",idempotencyKey:k1})).status,400);
 assert.equal((await call({handle:"@"+senderHandle,amount:"1",idempotencyKey:k1})).status,400,"cannot transfer to self");
 assert.equal((await call({handle:"@missing1",amount:"1",idempotencyKey:k1})).status,400);
 assert.equal((await call({handle:"@"+recipientHandle,amount:"41",idempotencyKey:k1})).status,409,"reserved balance cannot be sent");
 assert.equal(await prisma.send.count({where:{senderUserId:senderId}}),0);
 const data={handle:"@"+recipientHandle,amount:"20.123456",idempotencyKey:k1,saveRecipient:true,recipientName:"Recipient"};
 const success=await call(data);
 assert.equal(success.status,201);
 const result=await success.json();
 assert.equal(result.status,"COMPLETED");
 assert.equal((await prisma.user.findUniqueOrThrow({where:{id:senderId}})).unallocated,29_876_544n);
 assert.equal((await prisma.user.findUniqueOrThrow({where:{id:recipientId}})).unallocated,30_123_456n,"recipient credited within same committed transaction");
 const row=await prisma.send.findUniqueOrThrow({where:{id:result.id}});
 assert.equal(row.amount,20_123_456n);
 assert.equal(row.senderHandle,senderHandle);
 assert.equal(row.recipientHandle,recipientHandle);
 assert.equal((await prisma.userRecipient.findFirstOrThrow({where:{userId:senderId,kind:"SEND"}})).name,"Recipient");
 const duplicate=await call(data);
 assert.equal(duplicate.status,200);
 assert.equal((await duplicate.json()).id,row.id);
 assert.equal((await call({...data,amount:"19.000000"})).status,409,"reusing a request key for a different amount must be rejected");
 assert.equal((await prisma.user.findUniqueOrThrow({where:{id:senderId}})).unallocated,29_876_544n,"duplicate key cannot debit twice");
 assert.equal(await prisma.send.count({where:{senderUserId:senderId}}),1);
 assert.equal((await call({handle:"@"+recipientHandle,amount:"20",idempotencyKey:k2})).status,409,"balance after reserving pending withdrawal must be respected");
 assert.equal((await call({handle:"@"+recipientHandle,amount:"19.876544",idempotencyKey:k3})).status,201);
 assert.equal((await prisma.user.findUniqueOrThrow({where:{id:senderId}})).unallocated,10_000_000n);
 assert.equal((await prisma.user.findUniqueOrThrow({where:{id:recipientId}})).unallocated,50_000_000n);
 assert.equal(await prisma.send.count({where:{senderUserId:senderId}}),2);
 console.log("Fee-free sends checked: decimal precision, no self-send, recipient resolution, reserved funds, same-transaction credit, saved recipient, and idempotency");
}finally{
 await prisma.send.deleteMany({where:{senderUserId:senderId}});
 await prisma.userRecipient.deleteMany({where:{userId:senderId}});
 await prisma.withdrawal.deleteMany({where:{userId:senderId}});
 await prisma.user.deleteMany({where:{id:{in:[senderId,recipientId]}}});
 await prisma.$disconnect();
}
